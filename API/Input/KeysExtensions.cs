            Keys.LeftShift => "Shift",
            Keys.LeftControl => "Ctrl",
            Keys.LeftAlt => "Alt",
            Keys.OemSemicolon => ";",
            Keys.OemPlus => "+",
            Keys.OemComma => ",",
            Keys.OemMinus => "-",
            Keys.OemPeriod => ".",
            Keys.OemQuestion => "QM",
            Keys.OemTilde => "~",
            Keys.OemOpenBrackets => "[",
            Keys.OemCloseBrackets => "]",
            Keys.OemQuotes => "Quot",
            _ => throw new ArgumentOutOfRangeException(nameof(key))
        });
    }

    public static string FormatGlyph(string name) => $"/i[K{name}]";
}